def locomotor_line(lines):
    for part in split_object(lines):
        if part[0] == "field" and words(part[1])[:3] == ["Locomotor", "=", "SET_NORMAL"]:
            return part[1].strip()
    return None


def plane_text(name, jet_lines, ai_module, power, weapon_rename=None):
    parts = split_object(jet_lines)
    keep = lambda kind, mtype, tag: mtype not in PLANE_MODULES_TO_DROP
    rename = None
    if weapon_rename:
        def rename(line):
            for old, new in weapon_rename.items():
                line = re.sub(r"\b%s\b" % re.escape(old), new, line)
            return line
    modules = [ai_module, f"  Behavior = SortieLossDie ModuleTag_CoHLoss\n    SpecialPower = {power}\n  End\n"]
    text = object_text(name, parts, kindof_without(jet_lines, {"SELECTABLE"}, []),
                       extra_fields=["RadarPriority = UNIT"], extra_modules=modules, drop_fields=PLANE_FIELDS_TO_DROP,
                       keep_module=keep, fields_after_modules=[locomotor_line(jet_lines)])
    if weapon_rename:
        for old, new in weapon_rename.items():
            text = re.sub(r"(Weapon\s*=\s*\w+\s+)%s\b" % re.escape(old), r"\g<1>%s" % new, text)
    return text


