"""CoH UnitScale: writes the UnitScale pack from the retail INI.

Vehicles are drawn bigger and infantry smaller, so a tank is several soldiers long, as in CoH:
  INI/10_UnitScale.ini   for every faction unit, by class (FACTORS below):
                           Scale                       the model's size
                           GeometryMajorRadius/Minor/  the size the game logic sees, scaled with the model
                           Height                      so shots hit the hull, units don't overlap and the
                                                       selection box fits (infantry keep their radius, see
                                                       INFANTRY_KEEPS_RADIUS)
                           ShadowSizeX/Y               decal shadows (volume shadows follow the model)
                         and the same factor for what a unit leaves or carries: its hulk, and the add-ons
                         that ride on it (the Overlord's and Helix's gattling, bunker and speaker tower)

Each factor is the size on screen. The engine applies an object's Scale twice (it scales the model's
mesh when it makes it and the drawn transform again, W3DModelDraw::doDrawModule), so the pack writes
Scale = factor ** (1 / RENDER_POWER). The bones the logic fires from are measured the same way, so
muzzles stay on the barrels.

Run it again after changing it; it reads INIZH.big from the game folder:
    python CoH/Features/UnitScale/Data/make_pack.py [--preset <name>] [--out <folder>] ["<Zero Hour folder>"]
--preset writes one of PRESETS instead of FACTORS (to compare them in game; "retail" scales nothing);
--out writes elsewhere.
"""

import math
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "Tools"))
from retail import GAME_DIR, read_big  # noqa: E402

# ---- Tuning --------------------------------------------------------------------------------------

# The size on screen of each class, against retail. A retail soldier is about 0.43 of a tank's length;
# in CoH it is about 0.3 (1.8 m against a 6 m tank).
PRESETS = {
    "retail": {"tank": 1.0, "artillery": 1.0, "light": 1.0, "helicopter": 1.0, "jet": 1.0, "infantry": 1.0},
    "subtle": {"tank": 1.15, "artillery": 1.15, "light": 1.10, "helicopter": 1.15, "jet": 1.0, "infantry": 0.90},
    "coh":    {"tank": 1.25, "artillery": 1.25, "light": 1.15, "helicopter": 1.20, "jet": 1.0, "infantry": 0.85},
    "big":    {"tank": 1.40, "artillery": 1.35, "light": 1.25, "helicopter": 1.30, "jet": 1.0, "infantry": 0.80},
}
FACTORS = PRESETS["coh"]

# The engine applies Scale this many times (see the docstring).
RENDER_POWER = 2

# Infantry keep their retail radius: their spacing, their footprint and Accuracy's target size stay
# as they are, and only their height follows the smaller model.
INFANTRY_KEEPS_RADIUS = True

# Ground vehicles that fire from afar; matched on the name without a general's prefix (Lazr_...).
ARTILLERY = {"AmericaVehicleTomahawk", "ChinaVehicleInfernoCannon", "ChinaVehicleNukeLauncher",
             "GLAVehicleScudLauncher", "GLAVehicleScudLauncherHiDef"}
# Draw modules of tracked, armoured vehicles.
TANK_DRAWS = {"W3DTankDraw", "W3DOverlordTankDraw", "W3DOverlordTruckDraw"}
# Not tanks, whatever they are drawn with.
LIGHT_KINDS = {"DOZER", "HARVESTER", "TRANSPORT", "DRONE"}
# Files with units that aren't the factions' own: cinematics, civilians, props, map pieces.
SKIPPED_FILES = re.compile(r"CINE|Civilian|Nature|Hulk|System|WeaponObjects|TechBuildings|FactionBuilding|"
                           r"FactionProp|Buildings", re.IGNORECASE)
# Map pieces drawn as units (the battleships), by size.
MAX_UNIT_RADIUS = 100.0
# What a unit's object creation lists make that is drawn as part of the unit.
FOLLOWER_KINDS = {"HULK", "PORTABLE_STRUCTURE"}
DECAL_SHADOWS = {"SHADOW_DECAL", "SHADOW_ALPHA_DECAL", "SHADOW_ADDITIVE_DECAL"}

PATHFIND_CELL = 10.0
PACK_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "INI")
HEADER = "; CoH UnitScale: generated by Data/make_pack.py from the retail INI. Don't edit; run it again.\n"


# ---- Reading the retail INI ----------------------------------------------------------------------

def lines_of(text):
    """(starts a top-level block, words) for each line with content."""
    for raw in text.splitlines():
        line = raw.split(";", 1)[0].split("//", 1)[0].rstrip()
        if line.strip():
            yield not line[0].isspace(), line.replace("=", " = ").split()


def new_object(name, file_name, parent=None):
    return {"name": name, "file": file_name, "parent": parent, "kinds": None, "draws": [], "behaviors": set(),
            "geometry": {}, "shadow": None, "shadow_size": {}, "scale": None, "tokens": set()}


def parse_objects(files):
    """Every object, reskin and child object, read only as far as the pack needs.

    A block's header is the one line of it that isn't indented, so the many kinds of nested blocks
    don't need to be known. Within an object, the first KindOf is the object's own (module KindOf
    filters come after it); geometry, shadow and Scale lines only appear at the object's level.
    """
    objects = {}
    for file_name in sorted(files):
        if "object" not in re.split(r"[\\/]", file_name.lower()):
            continue
        current = None
        for top, words in lines_of(files[file_name]):
            head = words[0]
            if top:
                current = None
                if head == "Object" and len(words) > 1:
                    current = objects[words[1]] = new_object(words[1], file_name)
                elif head in ("ObjectReskin", "ChildObject") and len(words) > 2:
                    current = objects[words[1]] = new_object(words[1], file_name, parent=words[2])
                continue
            if current is None:
                continue
            current["tokens"].update(words)
            if head == "Draw" and len(words) > 2:
                current["draws"].append(words[2])
            elif head == "Behavior" and len(words) > 2:
                current["behaviors"].add(words[2])
            else:
                read_object_field(current, words)
    return objects


def real(word):
    """A number as the engine's INI::scanReal reads it: the leading number of the word (retail has "40v.0")."""
    match = re.match(r"[-+]?\d*\.?\d*", word)
    return float(match.group(0)) if match and match.group(0) not in ("", ".", "-", "+") else 0.0


def read_object_field(obj, words):
    head = words[0]
    if head == "KindOf" and obj["kinds"] is None:
        obj["kinds"] = set(words[2:])
    elif head in ("GeometryMajorRadius", "GeometryMinorRadius", "GeometryHeight") and len(words) > 2:
        obj["geometry"][head] = real(words[2])
    elif head == "Geometry" and len(words) > 2:
        obj["geometry"]["Geometry"] = words[2]
    elif head == "Shadow" and len(words) > 2:
        obj["shadow"] = words[2]
    elif head in ("ShadowSizeX", "ShadowSizeY") and len(words) > 2:
        obj["shadow_size"][head] = real(words[2])
    elif head == "Scale" and len(words) > 2:
        obj["scale"] = real(words[2])


def resolve(objects, name, field, seen=()):
    """A field of an object, from its parent when it doesn't set it itself."""
    obj = objects.get(name)
    if obj is None or name in seen:
        return None
    value = obj[field]
    if value in (None, {}, [], set()) and obj["parent"]:
        return resolve(objects, obj["parent"], field, seen + (name,))
    return value


def merged(objects, name, field, seen=()):
    """A dict field of an object over its parent's (a reskin keeps the base's geometry it doesn't set)."""
    obj = objects.get(name)
    if obj is None or name in seen:
        return {}
    base = merged(objects, obj["parent"], field, seen + (name,)) if obj["parent"] else {}
    return {**base, **obj[field]}


def parse_ocls(files):
    """Object creation list name -> the objects its CreateObject nuggets make."""
    ocls = {}
    for file_name, text in files.items():
        if not file_name.lower().endswith("objectcreationlist.ini"):
            continue
        current, in_create = None, False
        for top, words in lines_of(text):
            if top:
                current = ocls.setdefault(words[1], []) if words[0] == "ObjectCreationList" and len(words) > 1 else None
                in_create = False
            elif current is not None:
                if words[0] == "CreateObject":
                    in_create = True
                elif words[0] == "End":
                    in_create = False
                elif in_create and words[0] == "ObjectNames":
                    current.extend(words[2:])
    return ocls


# ---- Deciding --------------------------------------------------------------------------------------

def base_name(name):
    return name.split("_", 1)[1] if re.match(r"^[A-Za-z]+_", name) else name


def unit_class(objects, name):
    """The FACTORS class of a faction unit, or None for anything else."""
    obj = objects[name]
    kinds = resolve(objects, name, "kinds") or set()
    draws = resolve(objects, name, "draws") or []
    geometry = merged(objects, name, "geometry")
    if SKIPPED_FILES.search(obj["file"]) or not draws or not kinds & {"INFANTRY", "VEHICLE"}:
        return None
    if geometry.get("GeometryMajorRadius", 0.0) > MAX_UNIT_RADIUS:
        return None
    if "INFANTRY" in kinds:
        return "infantry"
    if "AIRCRAFT" in kinds:
        behaviors = resolve(objects, name, "behaviors") or set()
        helicopter = "PRODUCED_AT_HELIPAD" in kinds or "HelicopterSlowDeathBehavior" in behaviors
        return "helicopter" if helicopter else "jet"
    if base_name(name) in ARTILLERY:
        return "artillery"
    if draws[0] in TANK_DRAWS and not kinds & LIGHT_KINDS:
        return "tank"
    return "light"


def followers(objects, ocls, name):
    """Hulks and add-ons a unit's object creation lists make."""
    found = set()
    for token in resolve(objects, name, "tokens") or set():
        for made in ocls.get(token, []):
            if made in objects and (resolve(objects, made, "kinds") or set()) & FOLLOWER_KINDS:
                found.add(made)
    return found


def scaled_objects(objects, ocls, factors):
    """Object name -> (class, factor), for the units and what follows them. A hulk several units leave
    takes the biggest of their factors."""
    units = {name: unit_class(objects, name) for name in objects}
    chosen = {name: (cls, factors[cls]) for name, cls in units.items() if cls and factors[cls] != 1.0}
    following = {}
    for name, (cls, factor) in sorted(chosen.items()):
        for made in followers(objects, ocls, name):
            if units.get(made) is None and factor > following.get(made, ("", 0.0))[1]:
                following[made] = (f"{cls} (follows {name})", factor)
    return {**chosen, **following}


def pathfind_cells(radius):
    """The footprint in pathfinding cells the engine gives a unit of this bounding radius
    (Pathfinder::getRadiusAndCenter): 1 to 5 cells across."""
    diameter = 2 * radius
    if PATHFIND_CELL < diameter < 2 * PATHFIND_CELL:
        diameter = 2 * PATHFIND_CELL
    cells = max(int(math.floor(diameter / PATHFIND_CELL + 0.3)), 1)
    return min(cells, 5)


def bounding_radius(geometry):
    major = geometry.get("GeometryMajorRadius", 0.0)
    minor = geometry.get("GeometryMinorRadius", major)
    return math.hypot(major, minor) if geometry.get("Geometry", "").upper() == "BOX" else major


# ---- Writing ---------------------------------------------------------------------------------------

def number(value, places=2):
    return f"{value:.{places}f}".rstrip("0").rstrip(".")


def object_text(objects, name, cls, factor):
    geometry = merged(objects, name, "geometry")
    keep_radius = cls == "infantry" and INFANTRY_KEEPS_RADIUS
    own_scale = resolve(objects, name, "scale") or 1.0
    lines = [f"Object {name} ; {cls} x{number(factor)}\n",
             f"  Scale = {number(own_scale * factor ** (1.0 / RENDER_POWER), 3)}\n"]
    for field in ("GeometryMajorRadius", "GeometryMinorRadius"):
        if field in geometry and not keep_radius:
            lines.append(f"  {field} = {number(geometry[field] * factor)}\n")
    if "GeometryHeight" in geometry:
        lines.append(f"  GeometryHeight = {number(geometry['GeometryHeight'] * factor)}\n")
    if resolve(objects, name, "shadow") in DECAL_SHADOWS:
        for field, size in sorted(merged(objects, name, "shadow_size").items()):
            lines.append(f"  {field} = {number(size * factor)}\n")
    lines.append("End\n\n")
    return "".join(lines)


def pack_text(objects, chosen, factors):
    out = [HEADER, "; Size on screen by class: " + ", ".join(f"{k} x{number(v)}" for k, v in factors.items()) + "\n\n"]
    for name in sorted(chosen):
        out.append(object_text(objects, name, *chosen[name]))
    return "".join(out)


def footprint_report(objects, chosen):
    """Units whose pathfinding footprint grows, for the README."""
    rows = []
    for name, (cls, factor) in sorted(chosen.items()):
        geometry = merged(objects, name, "geometry")
        if "follows" in cls or not geometry or (cls == "infantry" and INFANTRY_KEEPS_RADIUS):
            continue
        before = pathfind_cells(bounding_radius(geometry))
        after = pathfind_cells(bounding_radius(geometry) * factor)
        if before != after and "_" not in name:
            rows.append(f"  {name}: {before} -> {after} cells")
    return rows


def main():
    args = sys.argv[1:]
    factors, out_dir = FACTORS, PACK_DIR
    if "--preset" in args:
        i = args.index("--preset")
        factors = PRESETS[args[i + 1]]
        del args[i:i + 2]
    if "--out" in args:
        i = args.index("--out")
        out_dir = args[i + 1]
        del args[i:i + 2]
    game_dir = args[0] if args else GAME_DIR

    files = read_big(os.path.join(game_dir, "INIZH.big"))
    objects = parse_objects(files)
    chosen = scaled_objects(objects, parse_ocls(files), factors)

    text = pack_text(objects, chosen, factors)
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "10_UnitScale.ini"), "w", newline="\r\n") as f:
        f.write(text)

    counts = {}
    for cls, _ in chosen.values():
        key = cls.split(" ")[0] + (" follower" if "follows" in cls else "")
        counts[key] = counts.get(key, 0) + 1
    print(f"10_UnitScale.ini: {len(chosen)} objects: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))
    print("Pathfinding footprints that grow (base units):")
    print("\n".join(footprint_report(objects, chosen)) or "  none")


if __name__ == "__main__":
    main()
