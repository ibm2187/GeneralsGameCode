"""CoH Sectors: writes the generated part of the Sectors pack from the retail INI.

Supplies come only from sectors, so the pack takes the supply buildings out of the game:
  INI/20_CommandSets.ini   empties every builder slot that constructs a supply center, supply stash
                           or supply drop zone ("None", one slot per line, so other packs that change
                           the same command sets still add up)
  INI/30_Prerequisites.ini rewrites every prerequisite on those buildings to the same general's
                           barracks, so the war factory, airfield, Chinook and the rest stay buildable
  INI/40_TechBuildings.ini removes the oil derricks' own income; their sector pays instead

Run it again after changing it; it reads INIZH.big from the game folder:
    python CoH/Features/Sectors/Data/make_pack.py ["<Zero Hour folder>"]
"""

import os
import re
import struct
import sys

GAME_DIR = r"C:\Program Files (x86)\Steam\steamapps\common\Command & Conquer Generals - Zero Hour"
PACK_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "INI")
SUPPLY_KINDS = {"FS_SUPPLY_CENTER", "FS_SUPPLY_DROPZONE"}
HIGH_VALUE_KINDS = {"TECH_BUILDING"}
HEADER = "; CoH Sectors: generated by Data/make_pack.py from the retail INI. Don't edit; run it again.\n"


def read_big(path):
    """The INI files of a .big archive, as {name: text}."""
    with open(path, "rb") as f:
        data = f.read()
    count = struct.unpack(">I", data[8:12])[0]
    files, pos = {}, 16
    for _ in range(count):
        offset, size = struct.unpack(">II", data[pos:pos + 8])
        end = data.index(b"\0", pos + 8)
        name = data[pos + 8:end].decode("latin-1")
        pos = end + 1
        if name.lower().endswith(".ini"):
            files[name] = data[offset:offset + size].decode("latin-1")
    return files


def lines_of(text):
    """(starts a top-level block, words) for each line with content."""
    for raw in text.splitlines():
        line = raw.split(";", 1)[0].split("//", 1)[0].rstrip()
        if line.strip():
            yield not line[0].isspace(), line.replace("=", " = ").split()


def parse(files):
    """Objects, command buttons and command sets, read only as far as the pack needs them.

    A block's header is the one line of it that isn't indented, so the many kinds of nested blocks
    don't need to be known. Within an object, the first KindOf is the object's own (module KindOf
    filters come after it).
    """
    objects = {}     # name -> {"kinds": set, "prereqs": [[names]] or None, "deposits": [tags]}
    buttons = {}     # name -> {"command": str, "object": str}
    sets = {}        # name -> {slot: button}
    for file_name in sorted(files):
        block, current, in_prereqs = None, None, False
        for top, words in lines_of(files[file_name]):
            head = words[0]
            if top and head != "End":
                block, current, in_prereqs = None, None, False
                if head in ("Object", "ChildObject") and len(words) > 1 and words[1] != "=":
                    block = "object"
                    current = objects.setdefault(words[1], {"kinds": None, "prereqs": None, "deposits": []})
                elif head == "CommandButton" and len(words) > 1:
                    block, current = "button", buttons.setdefault(words[1], {"command": "", "object": ""})
                elif head == "CommandSet" and len(words) > 1:
                    block, current = "set", sets.setdefault(words[1], {})
                continue
            if current is None:
                continue

            if block == "button":
                if head == "Command" and len(words) > 2:
                    current["command"] = words[2]
                elif head == "Object" and len(words) > 2:
                    current["object"] = words[2]
            elif block == "set":
                if head.isdigit() and len(words) > 2:
                    current[int(head)] = words[2]
            elif in_prereqs:
                if head == "End":
                    in_prereqs = False
                elif head == "Object":
                    current["prereqs"].append(words[2:])
                elif head == "Science":
                    current["prereqs"].append(["Science"] + words[2:])
            elif head == "KindOf" and current["kinds"] is None:
                current["kinds"] = set(words[2:])
            elif head == "Prerequisites" and len(words) == 1:
                current["prereqs"], in_prereqs = [], True
            elif head == "Behavior" and len(words) > 3 and words[2] == "AutoDepositUpdate":
                current["deposits"].append(words[3])

    for info in objects.values():
        info["kinds"] = info["kinds"] or set()
        info["prereqs"] = info["prereqs"] or []
    return objects, buttons, sets


def is_supply_building(objects, name):
    return bool(objects.get(name, {}).get("kinds", set()) & SUPPLY_KINDS)


def barracks_for(objects, name):
    for supply in ("SupplyCenter", "SupplyStash", "SupplyDropZone"):
        if supply in name:
            candidate = name.replace(supply, "Barracks")
            if candidate in objects:
                return candidate
    return None


def command_sets_text(objects, buttons, sets):
    out = [HEADER]
    for set_name in sorted(sets):
        slots = [slot for slot, button in sorted(sets[set_name].items())
                 if buttons.get(button, {}).get("command") == "DOZER_CONSTRUCT"
                 and is_supply_building(objects, buttons[button]["object"])]
        if not slots:
            continue
        out.append(f"CommandSet {set_name}\n")
        for slot in slots:
            out.append(f"  {slot} = None ; was {sets[set_name][slot]}\n")
        out.append("End\n\n")
    return "".join(out)


def is_supply_truck(objects, name):
    kinds = objects[name]["kinds"]
    return "HARVESTER" in kinds and not kinds & {"DOZER", "TRANSPORT"}


def prerequisites_text(objects):
    out = [HEADER]
    for name in sorted(objects):
        if is_supply_truck(objects, name):
            continue  # built only at supply centers, which are gone
        prereqs = objects[name]["prereqs"]
        if not any(is_supply_building(objects, n) for line in prereqs if line[0] != "Science" for n in line):
            continue
        out.append(f"Object {name}\n  Prerequisites\n")
        for line in prereqs:
            if line[0] == "Science":
                out.append(f"    Science = {' '.join(line[1:])}\n")
                continue
            kept = []
            for n in line:
                if not is_supply_building(objects, n):
                    kept.append(n)
                elif (barracks := barracks_for(objects, n)) and barracks not in kept:
                    kept.append(barracks)
            if kept:
                out.append(f"    Object = {' '.join(kept)}\n")
        out.append("  End\nEnd\n\n")
    return "".join(out)


def tech_buildings_text(objects):
    out = [HEADER]
    for name in sorted(objects):
        info = objects[name]
        if info["kinds"] & HIGH_VALUE_KINDS and info["deposits"]:
            out.append(f"Object {name}\n")
            for tag in info["deposits"]:
                out.append(f"  RemoveModule {tag} ; its AutoDepositUpdate\n")
            out.append("End\n\n")
    return "".join(out)


def main():
    game_dir = sys.argv[1] if len(sys.argv) > 1 else GAME_DIR
    files = read_big(os.path.join(game_dir, "INIZH.big"))
    objects, buttons, sets = parse(files)
    outputs = {
        "20_CommandSets.ini": command_sets_text(objects, buttons, sets),
        "30_Prerequisites.ini": prerequisites_text(objects),
        "40_TechBuildings.ini": tech_buildings_text(objects),
    }
    for file_name, text in outputs.items():
        with open(os.path.join(PACK_DIR, file_name), "w", newline="\r\n") as f:
            f.write(text)
        print(f"{file_name}: {text.count(chr(10) + 'End' + chr(10))} blocks")


if __name__ == "__main__":
    main()
