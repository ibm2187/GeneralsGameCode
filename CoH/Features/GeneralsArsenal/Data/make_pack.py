# ---- Reading the retail INI -----------------------------------------------------------------------

TOP = ("Object", "ObjectReskin", "CommandSet", "CommandButton", "SpecialPower", "Science", "PlayerTemplate",
       "Weapon", "ObjectCreationList", "Locomotor", "Upgrade")


def read_big(path):
    """The INI files of a .big archive, as {name: text}."""
    with open(path, "rb") as f:
        data = f.read()
    count = struct.unpack(">I", data[8:12])[0]
    files, pos = {}, 16
    for _ in range(count):
        offset, size = struct.unpack(">II", data[pos:pos + 8])
        end = data.index(b"\0", pos + 8)
        name = data[pos + 8:end].decode("latin-1")
        pos = end + 1
        if name.lower().endswith(".ini"):
            files[name] = data[offset:offset + size].decode("latin-1")
    return files


def clean(line):
    return line.split(";", 1)[0].split("//", 1)[0].rstrip()


def words(line):
    return clean(line).replace("=", " = ").split()


def read_blocks(files):
    """{(kind, name): [lines]} of every top-level block, its header line first; the first definition wins."""
    out = {}
    for name in sorted(files):
        if "\\default\\" in name.lower():
            continue
        cur, lines = None, []
        for raw in files[name].splitlines():
            stripped = clean(raw)
            if stripped and not stripped[0].isspace():
                w = stripped.replace("=", " = ").split()
                if w[0] in TOP and len(w) > 1:
                    if cur and cur not in out:
                        out[cur] = lines
                    cur, lines = (w[0], w[1]), [raw]
                    continue
            if cur:
                lines.append(raw)
        if cur and cur not in out:
            out[cur] = lines
    return out


def opens_block(w):
    """Whether a line with these words starts a nested block that ends with End."""
    head = w[0]
    if head in ("Draw", "Body", "Behavior", "ClientUpdate", "ConditionState", "ModelConditionState", "TransitionState",
                "ReplaceModule"):
        return True
    return len(w) == 1 and head in ("ArmorSet", "WeaponSet", "Prerequisites", "UnitSpecificSounds", "UnitSpecificFX",
                                     "Turret", "AltTurret", "DefaultConditionState", "DeliveryDecal", "FlightPath",
                                     "AddModule", "InheritableModule", "OverrideableByLikeKind", "DeliverPayload",
                                     "CreateObject", "FireWeapon", "Attack", "ApplyRandomForce", "CreateDebris",
                                     "WeaponOCL")


def split_object(lines):
    """An object's body as [("field", line) | ("block", head words, [lines]) | ("module", kind, type, tag, [lines])]."""
    parts, depth, cur = [], 0, None
    for raw in lines[1:]:
        w = words(raw)
        if not w:
            if cur is not None:
                cur[-1].append(raw)
            continue
        if depth == 0:
            if w[0] in ("End", "END"):
                break
            if w[0] in ("Draw", "Body", "Behavior", "ClientUpdate") and len(w) >= 4:
                cur = ["module", w[0], w[2], w[3], [raw]]
                depth = 1
            elif opens_block(w):
                cur = ["block", w, [raw]]
                depth = 1
            else:
                parts.append(("field", raw))
            continue
        cur[-1].append(raw)
        if w[0] in ("End", "END"):
            depth -= 1
            if depth == 0:
                parts.append(tuple(cur))
                cur = None
        elif opens_block(w):
            depth += 1
    return parts


def field(lines, key):
    """The words after 'key =' of the first top-level field of a block, or None."""
    for part in split_object(lines):
        if part[0] == "field":
            w = words(part[1])
            if w and w[0] == key:
                return w[2:] if len(w) > 1 and w[1] == "=" else w[1:]
    return None


def any_field(lines, key):
    """Like field(), but anywhere in the block, nested or not."""
    for raw in lines[1:]:
        w = words(raw)
        if w and w[0] == key:
            return w[2:] if len(w) > 1 and w[1] == "=" else w[1:]
    return None


def kinds(lines):
    return set(field(lines, "KindOf") or [])


def command_set(blocks, name):
    res = {}
    for raw in blocks.get(("CommandSet", name), [])[1:]:
        w = words(raw)
        if w and w[0].isdigit() and len(w) > 2:
            res[int(w[0])] = w[2]
    return res


def button(blocks, name):
    """(command, object, special power) of a command button."""
    lines = blocks.get(("CommandButton", name), [])
    first = lambda key: (any_field(lines, key) or [None])[0]
    return first("Command"), first("Object"), first("SpecialPower")


