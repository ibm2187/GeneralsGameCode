    """A copy of the neutron missile whose blasts hit harder and wider, with its weapon and OCL."""
    missile = blocks[("Object", "NeutronMissile")]
    body = scale_numbers(missile[1:], {f"Blast{i}MaxDamage" for i in range(1, 10)} |
                         {f"Blast{i}MinDamage" for i in range(1, 10)}, factor)
    body = scale_numbers(body, {f"Blast{i}InnerRadius" for i in range(1, 10)} |
                         {f"Blast{i}OuterRadius" for i in range(1, 10)}, 1.0 + (factor - 1.0) / 2)
    lines = [missile[0]] + body
    text = [object_text("CoHStrongNeutronMissile", split_object(lines), sorted(kinds(lines)))]
    weapon = blocks[("Weapon", "NeutronMissileWeapon")]
    text.append("Weapon CoHStrongNeutronMissileWeapon\n")
    text += [re.sub(r"\bNeutronMissile\b", "CoHStrongNeutronMissile", l) + "\n" for l in weapon[1:]]
    text.append("ObjectCreationList CoH_OCL_StrongNeutronMissile\n  FireWeapon\n    Weapon = CoHStrongNeutronMissileWeapon\n"
                "  End\nEnd\n\n")
    return "".join(text)


