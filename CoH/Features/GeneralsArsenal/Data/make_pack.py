def science_rank(blocks, science):
    lines = blocks.get(("Science", science), [])
    for s in field(lines, "PrerequisiteSciences") or []:
        m = re.match(r"SCIENCE_Rank(\d)", s)
        if m:
            return int(m.group(1))
    return None


def old_powers(blocks, g):
    """The General's powers a general already has on its command center: [(template, levels, ocls)]."""
    found = []
    cc_lines = blocks[("Object", g.cc)]
    modules = [p for p in split_object(cc_lines) if p[0] == "module"]
    for slot, b in sorted(command_set(blocks, g.cc_set).items()):
        command, _, power = button(blocks, b)
        if not power or command not in ("SPECIAL_POWER", "SPECIAL_POWER_CONSTRUCT"):
            continue
        required = (field(blocks.get(("SpecialPower", power), []), "RequiredScience") or [None])[0]
        sciences = any_field(blocks.get(("CommandButton", b), []), "Science") or ([required] if required else [])
        ocls, module_types, planes = [], [], []
        for _, mkind, mtype, tag, lines in modules:
            if any(words(l)[:3] == ["SpecialPowerTemplate", "=", power] for l in lines):
                module_types.append(mtype)
                for l in lines:
                    w = words(l)
                    if w and w[0] == "OCL" and len(w) > 2:
                        ocls.append(w[2])
                    elif w and w[0] == "UpgradeOCL" and len(w) > 3:
                        ocls.append(w[3])
                    elif w and w[0] == "GunshipTemplateName" and len(w) > 2:
                        planes.append(w[2])
        found.append((power, [s for s in sciences if s], ocls, module_types, planes))
    return found


def ocl_transports(blocks, ocl):
    lines = blocks.get(("ObjectCreationList", ocl), [])
    return [w[2] for w in (words(l) for l in lines) if w and w[0] == "Transport" and len(w) > 2]


def is_air_power(blocks, ocls, module_types):
    if any("Spectre" in t for t in module_types):
        return True
    for ocl in ocls:
        for transport in ocl_transports(blocks, ocl):
            if "AIRCRAFT" in kinds(blocks.get(("Object", transport), [])):
                return True
    return False


# ---- Writing --------------------------------------------------------------------------------------

def special_power_block(name, enum, cooldown, radius, extra=()):
    lines = [f"SpecialPower {name}\n"]
    if enum:
        lines.append(f"  Enum = {enum}\n")
    lines += [f"  ReloadTime = {int(cooldown * 1000)}\n", "  SharedSyncedTimer = Yes\n", "  PublicTimer = No\n",
              f"  RadiusCursorRadius = {radius}\n", "  ShortcutPower = Yes\n", "  AcademyClassify = ACT_SUPERPOWER\n"]
    lines += [f"  {e}\n" for e in extra]
    lines.append("End\n\n")
    return "".join(lines)


def cohpower_block(name, cost, rank, airfield, loss, ai, levels=(), description=None, ai_targets=None):
    lines = [f"CoHPower {name}\n", f"  Cost = {cost}\n", f"  MinRank = {rank}\n",
             f"  NeedsAirfield = {'Yes' if airfield else 'No'}\n", f"  LossPenalty = {loss}\n", f"  AIUse = {ai}\n"]
    if ai_targets:
        lines.append(f"  AITargetKinds = {ai_targets}\n")
    if description:
        lines.append(f"  Description = {description}\n")
    lines += [f"  Level = {science} {lvl_rank}\n" for science, lvl_rank in levels]
    lines.append("End\n\n")
    return "".join(lines)


def text_line(label, text):
    return f'  Text = {label} "{text}"\n'


def upgrade_sets(blocks, obj):
    """The command sets an object switches to on an upgrade (CommandSetUpgrade), such as the China
    airfield's set after the mines upgrade. They need the same changes as its own set."""
    names = []
    for part in split_object(blocks.get(("Object", obj), [])):
        if part[0] == "module" and part[2] == "CommandSetUpgrade":
            for line in part[4]:
                w = words(line)
                if w and w[0] in ("CommandSet", "CommandSetAlt") and len(w) > 2 and w[2] not in names:
                    names.append(w[2])
    return names


def builder_superweapon_slots(blocks, set_name):
    """The slots of a builder's set that construct a super weapon building."""
    slots = {}
    for slot, b in command_set(blocks, set_name).items():
        command, obj, _ = button(blocks, b)
        if command == "DOZER_CONSTRUCT" and "FS_SUPERWEAPON" in kinds(blocks.get(("Object", obj), [])):
            slots[slot] = obj
    return slots


def jet_slots(blocks, set_name):
    """The slots of an airfield's set that build a jet."""
    return [slot for slot, b in command_set(blocks, set_name).items()
            if button(blocks, b)[0] == "UNIT_BUILD" and "Jet" in (button(blocks, b)[1] or "")]


def first_free(slots, candidates):
    for s in candidates:
        if s not in slots:
            return s
    return None


def main():
    game_dir = sys.argv[1] if len(sys.argv) > 1 else GAME_DIR
    blocks = read_blocks(read_big(os.path.join(game_dir, "INIZH.big")))
    generals = survey(blocks)

    powers_ini, weapons_ini, objects_ini, ocl_ini, buttons_ini, buildings_ini, sets_ini = ([HEADER] for _ in range(7))
    texts = {}
    done_objects, done_weapons, done_powers, sciences_free = set(), set(), set(), set()
    loss_transports = {}

    for g in generals:
        new = powers_for(g)
        cc_slots = command_set(blocks, g.cc_set)
        airfield_slots = command_set(blocks, g.airfield_set) if g.airfield_set else {}
        cc_changes, airfield_changes, shortcut_buttons = {}, {}, []
        building_modules = {g.cc: [], g.airfield: []}

        for p in new:
            t = p["template"]
            name_label = p.get("label") or f"CONTROLBAR:CoH{g.faction}{p['key']}"
