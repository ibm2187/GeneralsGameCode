    # The power sciences are no longer bought: they come with rank.
    for science in sorted(sciences_free):
        if ("Science", science) in blocks:
            powers_ini.append(f"Science {science}\n  SciencePurchasePointCost = 0 ; comes with rank\nEnd\n\n")

