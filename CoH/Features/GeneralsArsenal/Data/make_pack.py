def host_object(blocks, building, power_renames, extra_modules=()):
    """A hidden copy of a super weapon building at the map edge that fires its weapon for the power."""
    lines = blocks[("Object", building)]
    parts = split_object(lines)
    keep = lambda kind, mtype, tag: mtype in HOST_MODULES

    def rename(line):
        for old, new in power_renames.items():
            line = re.sub(r"(SpecialPowerTemplate\s*=\s*)%s\b" % re.escape(old), r"\g<1>%s" % new, line)
        return line

    keep_fields = ("Geometry", "GeometryMajorRadius", "GeometryMinorRadius", "GeometryHeight", "GeometryIsSmall",
                   "ArmorSet", "WeaponSet", "DisplayName", "Side")
    filtered = []
    for part in parts:
        if part[0] == "field" and words(part[1])[0] not in keep_fields:
            continue
        if part[0] == "block" and part[1][0] not in keep_fields:
            continue
        filtered.append(part)
    name = f"CoHHost_{building}"
    return name, object_text(name, filtered, ["IMMOBILE", "UNATTACKABLE", "NO_SELECT", "IGNORED_IN_GUI", "INERT",
                                                "NO_COLLIDE"],
                             extra_fields=["RadarPriority = NOT_ON_RADAR", "VisionRange = 0", "ShroudClearingRange = 0"],
                             extra_modules=extra_modules, keep_module=keep, rename=rename)


