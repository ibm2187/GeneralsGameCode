def object_text(name, parts, kindof, extra_fields=(), extra_modules=(), drop_fields=(), keep_module=None,
                rename=None, fields_after_modules=()):
    """A new object from the parts of another: its modules filtered, some fields dropped or added.

    The pack loads like a map.ini, where a new object's modules must be inside AddModule.
    """
    out, modules = [f"Object {name}\n"], []
    for part in parts:
        if part[0] == "field":
            w = words(part[1])
            if not w or w[0] in drop_fields or w[0] == "KindOf":
                continue
            out.append(part[1] + "\n")
        elif part[0] == "block":
            if part[1][0] in drop_fields:
                continue
            out.extend(l + "\n" for l in part[2])
        else:
            _, mkind, mtype, tag, lines = part
            if keep_module and not keep_module(mkind, mtype, tag):
                continue
            text = [l + "\n" for l in lines]
            if rename:
                text = [rename(l) for l in text]
            modules.extend(text)
    out.append(f"  KindOf = {' '.join(kindof)}\n")
    out.extend(f"  {f}\n" for f in extra_fields)
    out.append("  AddModule\n")
    out.extend(modules)
    out.extend(extra_modules)
    out.append("  End\n")
    out.extend(f"  {f}\n" for f in fields_after_modules)
    out.append("End\n\n")
    return "".join(out)


def kindof_without(lines, remove, add):
    ks = [k for k in (field(lines, "KindOf") or []) if k not in remove]
    return ks + [k for k in add if k not in ks]


