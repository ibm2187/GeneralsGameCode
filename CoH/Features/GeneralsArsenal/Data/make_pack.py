def scale_numbers(lines, keys, factor):
    out = []
    for raw in lines:
        w = words(raw)
        if w and w[0] in keys and len(w) > 2:
            try:
                value = float(w[2])
                raw = re.sub(r"=\s*[-\d.]+", "= %.1f" % (value * factor), raw, count=1)
            except ValueError:
                pass
        out.append(raw)
    return out


