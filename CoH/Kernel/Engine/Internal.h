// CoH Kernel: how the Kernel's engine parts reach each other. Slices don't include this;
// they use Kernel/Kernel.h and Kernel/Hooks.h.

#pragma once

#include "Kernel/Domain/Feature.h"

#include <string>
#include <vector>

class AsciiString;
class GameInfo;
class UnicodeString;
class INI;
class ModuleFactory;
typedef void (*INIBlockParse)( INI *ini );

namespace CoH::Kernel
{

FeatureRegistry &registry();

// The flags this machine plays its own games with: Features.ini, or -coh on the command line.
const FeatureSet &localFlags();

// Registers every slice, reads the local flags and runs each slice's init.
void init();

// The arguments the game was started with, without the program name.
std::vector<std::string> processArguments();

FeatureSet readLocalFlags();

// Generated by CoH/CMakeLists.txt from its coh_add_feature lines.
void registerFeatures(FeatureRegistry &registry);

} // namespace CoH::Kernel

namespace CoH::GameFlags
{

AsciiString optionsFor(const GameInfo *game);
void onOptionsParsed(const GameInfo *game, const AsciiString &options);

// The flags the game being started plays with.
FeatureSet forNewGame(bool loadingSaveGame);

// The flags a save game being loaded was made with; cleared when the game ends.
void setSaved(const FeatureSet &flags);
void clearSaved();

} // namespace CoH::GameFlags

namespace CoH::Packs
{

// Loads the INI pack of every active feature, in registration order.
void loadActive(const FeatureRegistry &registry);

} // namespace CoH::Packs

namespace CoH::Registration
{

void addModulesTo(ModuleFactory &factory);
INIBlockParse findIniBlock(const char *token);

} // namespace CoH::Registration

namespace CoH::PackText
{

// The CoHText blocks of the active packs: text for labels the game's string file lacks, such as the
// names of a feature's new buttons. Forgotten when the game ends, with the packs.
void parseBlock(INI *ini);
const UnicodeString *find(const char *label);
void clear();

} // namespace CoH::PackText

namespace CoH::QuickSkirmish
{

// With -cohSkirmish on the command line: at engine init, turns off the intro and the shell map,
// like -loadsave does; once the shell is up, starts the skirmish against the AI.
bool isAsked();	///< -cohSkirmish is on the command line
void prepareIfAsked();
void startIfAsked();

// With -cohQuitAfter <seconds>: quits the game once that much game time has passed.
void quitIfDue();

} // namespace CoH::QuickSkirmish
